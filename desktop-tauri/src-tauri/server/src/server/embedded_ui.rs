//! **内嵌界面资源**（`--features embed-ui` 的单文件分发形态）。
//!
//! ── 它是什么 ────────────────────────────────────────────────
//! 一张「相对路径 → 字节」的静态表，由 `build.rs` 在编译期从
//! `desktop-tauri/ui/` 生成并 `include!` 进来。开了这个 feature，可执行文件
//! 里就带着整份面板（约 5 MB），**拷一个 exe 走就能跑**，不需要在旁边放
//! `ui/` 目录。
//!
//! ── 与磁盘形态的关系：磁盘优先，内嵌兜底 ────────────────────
//! `static_files::serve` 的取文件顺序是「先看 `ui/` 目录，找不到再查这张表」。
//! 顺序不能反：
//!   · 面板自更新（`core::update::selfupdate`）落地的是**磁盘上的 ui/**
//!     —— 内嵌表在编译期就固定了，优先它会让「更新界面」这件事失效；
//!   · 想临时改个文案的人也应该只要替换 `ui/` 里的文件，不必重编二进制。
//!
//! 所以内嵌表是**兜底**而不是**首选**：只要旁边有 `ui/`，行为与不开这个
//! feature 完全一样。
//!
//! ── 不开 feature 时 ─────────────────────────────────────────
//! `FILES` 是空表（`build.rs` 的产物），[`lookup`] 恒返回 `None`，
//! 静态服务照旧只看磁盘 —— 与本模块不存在时的行为逐字相同。
//!
//! ── 为什么查表用线性扫描 ────────────────────────────────────
//! 184 个条目、每次请求一遍字符串比较，量级是微秒；换成排序 + 二分要
//! 在 `build.rs` 里维护一个「排序口径必须与查表口径一致」的隐性约定，
//! 不划算。真到了需要优化的规模（上万条目）再说。

include!(concat!(env!("OUT_DIR"), "/embedded_ui.rs"));

/// 按相对路径（正斜杠，如 `app.js` / `icons/x.png`）查内嵌资源。
///
/// 返回 `(规范路径, 字节)`：路径取自表本身而不是入参，调用方据此判定
/// `index.html`（要注入网页端桥接）与扩展名（定 content-type）。
pub fn lookup(path: &str) -> Option<(&'static str, &'static [u8])> {
    FILES
        .iter()
        .find(|(name, _)| *name == path)
        .map(|(name, bytes)| (*name, *bytes))
}

/// 内嵌资源条目数（0 = 未开启 feature，或编译时界面目录缺失）。
///
/// 启动日志用它说明「面板是从 exe 里出的还是从磁盘出的」—— 单文件部署
/// 出问题时，这一行能直接排除「是不是 ui 目录没带」这类怀疑。
pub fn count() -> usize {
    FILES.len()
}
